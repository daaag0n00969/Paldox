def default_work(e1, e2, power):
    w = {}
    if e1 == "Fire" or e2 == "Fire":
        w["kindling"] = 2 if power < 600 else 1
    if e1 == "Water" or e2 == "Water":
        w["watering"] = 2 if power < 600 else 1
    if e1 == "Grass" or e2 == "Grass":
        w["planting"] = 2 if power < 600 else 1
    if e1 == "Electric" or e2 == "Electric":
        w["generating_electricity"] = 2 if power < 600 else 1
    if e1 == "Ice" or e2 == "Ice":
        w["cooling"] = 2 if power < 600 else 1
    if e1 == "Ground" or e2 == "Ground":
        w["mining"] = 2 if power < 600 else 1
    if power > 1000:
        w.setdefault("handiwork", 1)
        w.setdefault("gathering", 1)
    elif power > 500:
        w.setdefault("handiwork", 2)
        w.setdefault("transporting", 2)
    else:
        w.setdefault("handiwork", 3)
        w.setdefault("transporting", 3)
        w.setdefault("lumbering", 2)
    return w


