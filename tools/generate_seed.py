def main():
    dirs = [
        "app/src/main/java/com/paldexpro/data/local/entity",
        "app/src/main/java/com/paldexpro/data/local/dao",
        "app/src/main/java/com/paldexpro/data/local",
        "app/src/main/java/com/paldexpro/data/repository",
        "app/src/main/java/com/paldexpro/data/seed",
        "app/src/main/java/com/paldexpro/domain/model",
        "app/src/main/java/com/paldexpro/domain/breeding",
        "app/src/main/java/com/paldexpro/ui/theme",
        "app/src/main/java/com/paldexpro/ui/navigation",
        "app/src/main/java/com/paldexpro/ui/components",
        "app/src/main/java/com/paldexpro/ui/screens/home",
        "app/src/main/java/com/paldexpro/ui/screens/paldex",
        "app/src/main/java/com/paldexpro/ui/screens/breeding",
        "app/src/main/java/com/paldexpro/ui/screens/skills",
        "app/src/main/java/com/paldexpro/ui/screens/items",
        "app/src/main/java/com/paldexpro/ui/screens/bosses",
        "app/src/main/java/com/paldexpro/ui/screens/guides",
        "app/src/main/java/com/paldexpro/ui/screens/settings",
        "app/src/main/java/com/paldexpro/di",
        "app/src/main/res/values",
        "app/src/main/res/values-ru",
        "app/src/main/res/values-night",
        "app/src/main/res/xml",
        "app/src/main/res/drawable",
        "app/src/main/assets",
        "app/src/test/java/com/paldexpro",
        "gradle/wrapper",
    ]
    for d in dirs:
        (ROOT / d).mkdir(parents=True, exist_ok=True)

    seed = {
        "version": 1,
        "gameVersion": "1.0",
        "pals": [],
        "passives": [],
        "actives": [],
        "items": [],
        "bosses": [],
        "guides": [],
        "specialCombos": [],
        "sameSpeciesOnly": same_species_only,
    }

    for p in pals_raw:
        pid, dex, en, ru, e1, e2, power, eligible, idx, rarity = p
        hp, atk, deff, food = stats_for(rarity, power)
        work = work_overrides.get(pid) or default_work(e1, e2, power)
        ps = partner_skills.get(pid)
        seed["pals"].append({
            "id": pid,
            "dexNumber": dex,
            "nameEn": en,
            "nameRu": ru,
            "element1": e1,
            "element2": e2,
            "breedingPower": power,
            "eligibleChild": eligible,
            "indexNo": idx,
            "rarity": rarity,
            "hp": hp,
            "attack": atk,
            "defense": deff,
            "foodAmount": food,
            "eggSize": egg_by_rarity[rarity],
            "workSuitability": work,
            "partnerSkillId": ps[0] if ps else f"{pid}_skill",
            "partnerSkillNameEn": ps[1] if ps else f"{en} Partner Skill",
            "partnerSkillNameRu": ps[2] if ps else f"Навык партнёра {ru}",
            "partnerSkillDescEn": ps[3] if ps else f"Partner skill of {en}.",
            "partnerSkillDescRu": ps[4] if ps else f"Партнёрский навык {ru}.",
            "locationEn": BIOMES.get(e1, "Palpagos Islands"),
            "locationRu": BIOMES.get(e1, "Острова Палпагос"),
            "dropsEn": "Materials / Bones / Pal Fluids",
            "dropsRu": "Материалы / Кости / Пал-жидкости",
            "nightOnly": e1 == "Dark" and rarity in ("uncommon", "rare"),
        })

    for p in passives:
        seed["passives"].append({
            "id": p[0], "nameEn": p[1], "nameRu": p[2], "polarity": p[3],
            "tier": p[4], "descEn": p[5], "descRu": p[6],
        })
    for a in actives:
        seed["actives"].append({
            "id": a[0], "nameEn": a[1], "nameRu": a[2], "element": a[3],
            "power": a[4], "cooldown": a[5], "descEn": a[6], "descRu": a[7],
        })
    for i in items:
        seed["items"].append({
            "id": i[0], "nameEn": i[1], "nameRu": i[2], "category": i[3],
            "descEn": i[4], "descRu": i[5],
        })
    for b in bosses:
        seed["bosses"].append({
            "order": b[0], "id": b[1], "nameEn": b[2], "nameRu": b[3],
            "locationEn": b[4], "locationRu": b[5], "level": b[6],
            "element1": b[7], "element2": b[8], "strategyEn": b[9],
            "strategyRu": b[10], "counterPalIds": b[11],
        })
    for g in guides:
        seed["guides"].append({
            "id": g[0], "titleEn": g[1], "titleRu": g[2], "category": g[3],
            "bodyEn": g[4], "bodyRu": g[5],
        })
    for c in special_combos:
        seed["specialCombos"].append({"parentA": c[0], "parentB": c[1], "child": c[2]})

    out = ROOT / "app/src/main/assets/seed_data.json"
    out.write_text(json.dumps(seed, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size} bytes)")
    print(f"Pals={len(seed['pals'])} Passives={len(seed['passives'])} Actives={len(seed['actives'])} Special={len(seed['specialCombos'])}")


if __name__ == "__main__":
    main()
